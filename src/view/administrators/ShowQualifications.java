    public void addRatingPanelDish(String food, int numStars, String comment) {
        JPanel panel = new JPanel();
        panel.setLayout(new BoxLayout(panel, BoxLayout.Y_AXIS));
        panel.setBackground(Color.WHITE);
        panel.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(new Color(230, 230, 230), 1, true),
                BorderFactory.createEmptyBorder(10, 12, 10, 12)
        ));

        JLabel lbl_title = new JLabel(food);
        lbl_title.setFont(new Font("SansSerif", Font.BOLD, 14));
        lbl_title.setForeground(new Color(33, 37, 41));
        lbl_title.setAlignmentX(Component.LEFT_ALIGNMENT);
        panel.add(lbl_title);

        panel.add(Box.createVerticalStrut(6));

        JPanel starsRow = new JPanel();
        starsRow.setLayout(new FlowLayout(FlowLayout.LEFT, 4, 0));
        starsRow.setBackground(Color.WHITE);
        starsRow.setAlignmentX(Component.LEFT_ALIGNMENT);
        starsRow.setMaximumSize(new Dimension(Integer.MAX_VALUE, 32));

        JLabel lbl_stars = new JLabel("Calificación:");
        lbl_stars.setFont(new Font("SansSerif", Font.PLAIN, 12));
        lbl_stars.setForeground(new Color(108, 117, 125));
        starsRow.add(lbl_stars);

        String fullStarPath = "/view/image/starQualification.png";
        String emptyStarPath = "/view/image/starEmpty.png";
        ImageIcon fullStarIcon = new ImageIcon(getClass().getResource(fullStarPath));
        ImageIcon emptyStarIcon = new ImageIcon(getClass().getResource(emptyStarPath));

        for (int i = 0; i < 5; i++) {
            JLabel star = new JLabel(i < numStars ? fullStarIcon : emptyStarIcon);
            starsRow.add(star);
        }

        panel.add(starsRow);

        if (comment != null && !comment.trim().isEmpty()) {
            panel.add(Box.createVerticalStrut(8));

            JLabel lbl_comment = new JLabel("Comentario:");
            lbl_comment.setFont(new Font("SansSerif", Font.BOLD, 11));
            lbl_comment.setForeground(new Color(108, 117, 125));
            lbl_comment.setAlignmentX(Component.LEFT_ALIGNMENT);
            panel.add(lbl_comment);

            panel.add(Box.createVerticalStrut(3));

            JTextArea txt_comment = new JTextArea(comment);
            txt_comment.setFont(new Font("SansSerif", Font.PLAIN, 12));
            txt_comment.setForeground(new Color(52, 58, 64));
            txt_comment.setBackground(new Color(248, 249, 250));
            txt_comment.setLineWrap(true);
            txt_comment.setWrapStyleWord(true);
            txt_comment.setEditable(false);
            txt_comment.setFocusable(false);
            txt_comment.setBorder(BorderFactory.createCompoundBorder(
                    BorderFactory.createLineBorder(new Color(222, 226, 230), 1, true),
                    BorderFactory.createEmptyBorder(6, 8, 6, 8)
            ));

            txt_comment.setAlignmentX(Component.LEFT_ALIGNMENT);
            txt_comment.setMaximumSize(new Dimension(Integer.MAX_VALUE, 80));

            panel.add(txt_comment);
        }

        panel.setMaximumSize(new Dimension(Integer.MAX_VALUE, Short.MAX_VALUE));

        jpl_contentRatingsDish.add(panel);
        jpl_contentRatingsDish.add(Box.createVerticalStrut(8));
        jpl_contentRatingsDish.revalidate();
        jpl_contentRatingsDish.repaint();
    }

